export function normalizeLanguage(value: string): SupportedLanguage {
  return supportedLanguages.includes(value as SupportedLanguage) ? value as SupportedLanguage : "English";
}

export function translate(language: string, text: string) {
  const locale = normalizeLanguage(language);
  return locale === "English" ? text : translations[locale][text] ?? text;
}

export function languageLocale(language: string) {
  if (language === "Spanish") return "es-US";
  if (language === "Chinese") return "zh-CN";
  return "en-US";
}
